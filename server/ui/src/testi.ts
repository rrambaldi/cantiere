const CHIAVE_LINGUA = "forgia-lingua";
const LOCALE: Record<Lingua, string> = { it: "it-IT", en: "en-GB" };
const eLingua = (v: unknown): v is Lingua => v === "it" || v === "en";

function linguaIniziale(): Lingua {
  try {
    const salvata = localStorage.getItem(CHIAVE_LINGUA);
    if (eLingua(salvata)) return salvata;
  } catch {
    /* storage non disponibile: vale la lingua del browser */
  }
  const dalBrowser = navigator.language.slice(0, 2).toLowerCase();
  return eLingua(dalBrowser) ? dalBrowser : "it";
}

/** Lingua e testi correnti. Sono binding vivi: chi li importa vede il cambio al ridisegno dell'App. */
export let lingua: Lingua = linguaIniziale();
export let T: Testi = lingua === "it" ? it : { ...it, ...en };
export let locale = LOCALE[lingua];

export function impostaLingua(l: Lingua) {
  lingua = l;
  T = l === "it" ? it : { ...it, ...en };
  locale = LOCALE[l];
}

export function salvaLingua(l: Lingua) {
  try {
    localStorage.setItem(CHIAVE_LINGUA, l);
  } catch {
    /* storage non disponibile: la scelta non resta, il resto funziona */
  }
}
